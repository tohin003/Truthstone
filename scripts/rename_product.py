def render_plan(plan: Plan, verbose: bool = False) -> str:
    out = [f"Rename plan: {plan.old.display} → {plan.new.display}"]
    out.append("  spellings: " + " · ".join(f"{k} → {v}" for k, v in plan.pairs.items()))
    if plan.previously:
        out.append(f"  first mentions: {plan.new.display} (previously named {plan.previously})")
    if plan.rerun:
        out.append(f"  {plan.old.display} is already recorded as a former name: this is a re-run")
    if plan.delegates:
        out.append("\nRenamed first by their own tools:")
        out += [
            f"  python3 {shlex.join([d.script, *d.rename_args[:5]])} ...  ({d.summary})"
            for d in plan.delegates
        ]
    occurrences, files = plan.by_class()
    out.append("\nChanges by class (occurrences, files):")
    for name, count in sorted(occurrences.items(), key=lambda kv: (-kv[1], kv[0])):
        out.append(f"  {name:<24} {count:>6}  {files[name]:>4}")
    out.append(f"  {'total':<24} {sum(occurrences.values()):>6}  {len(plan.edited):>4} file(s) edited")

    directories = [m for m in plan.moves if m[2]]
    singles = [m for m in plan.moves if not m[2]]
    out.append(f"\nMoves (git mv): {len(directories)} director(ies), {len(singles)} single file(s)")
    for src, dst, _ in directories:
        count = sum(1 for p, t in plan.targets.items() if t.startswith(dst + "/") and p != t)
        out.append(f"  {src}/ → {dst}/   ({count} tracked files below)")
    out += [f"  {src} → {dst}" for src, dst, _ in singles]

    out.append(f"\nFiles to edit ({len(plan.edited)}):")
    for f in sorted(plan.edited, key=lambda f: f.path):
        detail = ", ".join(f"{k} {v}" for k, v in sorted(f.counts.items(), key=lambda kv: (-kv[1], kv[0])))
        where = f.path if f.path == f.target else f"{f.path} → {f.target}"
        out.append(f"  {where}  [{detail}]")
    if verbose:
        out.append("\nEvery distinct rewrite (token → token, count):")
        for (a, b), n in sorted(plan.tokens.items(), key=lambda kv: (-kv[1], kv[0])):
            out.append(f"  {a} → {b}  {n}")

    out.append("\nKept as written (historical records):")
    out += [f"  {h}" for h in plan.historical] or ["  (none)"]
    out.append("References left as written, so they still resolve (these paths do not move):")
    out += [f"  {p}" for p in plan.protected] or ["  (none)"]
    if plan.skipped:
        out.append("Not rewritten:")
        out += [f"  {s}" for s in plan.skipped]
    out.append("\nThen:")
    out += [f"  record {plan.old.display} as a former name in: {r}" for r in plan.registries]
    out += [
        f"  regenerate: python -m {m} --write   (and check it reports nothing)" for m in plan.regenerators
    ]
    out += [f"  re-pin: {p}" for p in plan.pins]
    out.append("  re-sort imports in the edited Python files: ruff check --select I --fix")
    out += [
        f"  lockfile: {p}  ({' / '.join(' '.join(c) for c in cmds)})" for p, cmds in plan.lockfiles.items()
    ]
    out.append("  validate the plugins; stage everything; audit what is left of the old name")
    if plan.warnings:
        out.append("\nWarnings:")
        out += [f"  {w}" for w in plan.warnings]
    if plan.unhandled:
        out.append("\nSpellings the rewrite does not cover (fix by hand, or mark them to keep):")
        out += [f"  {u}" for u in plan.unhandled]
    return "\n".join(out)


# ------------------------------------------------------------------------------ git & tools


def git(root: Path, *args: str) -> str:
    proc = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise Refused(f"git {' '.join(args)} failed: {proc.stderr.strip()}")
    return proc.stdout


def tracked_files(root: Path) -> list[str]:
    return [p for p in git(root, "ls-files", "-z").split("\0") if p]


def tree_state(root: Path) -> tuple[list[str], list[str]]:
    """(tracked changes, untracked files)."""
    changed, untracked = [], []
    for entry in filter(
        None, git(root, "status", "--porcelain=v1", "-z", "--untracked-files=all").split("\0")
    ):
        (untracked if entry.startswith("??") else changed).append(entry[3:])
    return changed, untracked


def default_python(root: Path) -> str:
    venv = root / ".venv" / "bin" / "python"
    return str(venv) if venv.exists() else sys.executable


def run(cmd: list[str], root: Path, env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, cwd=root, capture_output=True, text=True, env=env, check=False)


def python_env(root: Path) -> dict[str, str]:
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join(filter(None, [str(root / "src"), str(root), env.get("PYTHONPATH")]))
    return env


