@dataclass
class Delegate:
    """A package that renames itself: its script documents ``rename --slug NEW --display``."""

    script: str
    summary: str
    rename_args: list[str]


def discover_delegates(
    root: Path, texts: dict[str, str], kinds: dict[str, str], pattern: re.Pattern[str], pairs: dict[str, str]
) -> tuple[list[Delegate], list[str]]:
    delegates, warnings = [], []
    manifests: dict[str, dict] = {}
    candidates = [
        p for p in texts if p.endswith(("/.codex-plugin/plugin.json", "/.claude-plugin/plugin.json"))
    ]
    for path in sorted(candidates, key=lambda p: "/.codex-plugin/" not in p):  # Codex manifests first
        try:
            data = json.loads(texts[path])
        except ValueError:
            continue
        if isinstance(data, dict) and isinstance(data.get("name"), str):
            manifests.setdefault(data["name"], data)
    for path, text in sorted(texts.items()):
        usage = DELEGATE_USAGE.search(text) if kinds.get(path) == "living" and path.endswith(".py") else None
        if not usage or usage.group(1) != path:
            continue
        slug_match = re.search(r'^\w*SLUG\s*=\s*"([^"]+)"', text, re.M)
        manifest = manifests.get(slug_match.group(1)) if slug_match else None
        if not manifest:
            warnings.append(f"{path} documents a rename command, but its plugin manifest was not found")
            continue
        slug = manifest["name"]
        interface = manifest.get("interface") if isinstance(manifest.get("interface"), dict) else {}
        display = interface.get("displayName") or manifest.get("displayName") or ""
        developer = interface.get("developerName") or ""
        repository = manifest.get("repository") or ""
        new_slug, new_display = rename_text(slug, pattern, pairs), rename_text(display, pattern, pairs)
        if new_slug == slug and new_display == display:
            continue  # already renamed
        args = ["rename", "--slug", new_slug, "--display", new_display]
        if developer and rename_text(developer, pattern, pairs) != developer:
            args += ["--developer", rename_text(developer, pattern, pairs)]
        if repository.startswith("https://github.com/") and pattern.search(repository):
            args += ["--repo", rename_text(repository.removeprefix("https://github.com/"), pattern, pairs)]
        for old_spelling, new_spelling in pairs.items():
            if old_spelling not in (display, developer):
                args += ["--also", f"{old_spelling}={new_spelling}"]
        delegates.append(Delegate(path, f"{slug} → {new_slug} ({display} → {new_display})", args))
    return delegates, warnings


def self_checks(texts: dict[str, str], kinds: dict[str, str]) -> list[str]:
    """Scripts of self-renaming packages that also document ``python3 <script> check``."""
    found = []
    for path, text in sorted(texts.items()):
        usage = DELEGATE_USAGE.search(text) if kinds.get(path) == "living" and path.endswith(".py") else None
        if usage and usage.group(1) == path and re.search(rf"python3? {re.escape(path)} check\b", text):
            found.append(path)
    return found


