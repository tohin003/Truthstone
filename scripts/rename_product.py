def plugin_checks(root: Path, files: list[str]) -> tuple[list[str], list[str]]:
    """(Claude Code validate targets, Codex plugin ids its marketplace must list)."""
    claude = ["."] if ".claude-plugin/marketplace.json" in files else []
    claude += sorted(
        p[: -len("/.claude-plugin/plugin.json")] for p in files if p.endswith("/.claude-plugin/plugin.json")
    )
    codex: list[str] = []
    market = root / ".agents" / "plugins" / "marketplace.json"
    if ".agents/plugins/marketplace.json" in files:
        try:
            data = json.loads(market.read_text(encoding="utf-8"))
            codex = [f"{p['name']}@{data['name']}" for p in data.get("plugins", []) if isinstance(p, dict)]
        except (OSError, ValueError, KeyError, TypeError):
            codex = ["(unreadable marketplace)"]
    return claude, codex


def validate_plugins(
    root: Path, python: str, policy: dict[str, Any], claude_cli: str | None, codex_cli: str | None
) -> tuple[list[str], list[str]]:
    """Run every plugin validator with throwaway homes. Returns (report lines, problems)."""
    lines, problems = [], []
    files = tracked_files(root)
    kinds, texts = read_tree(root, files, policy)
    claude_targets, codex_ids = plugin_checks(root, files)
    for script in self_checks(texts, kinds):
        result = run([python, script, "check"], root)
        ok = result.returncode == 0
        lines.append(f"  {'ok ' if ok else 'FAIL'}  python3 {script} check")
        if not ok:
            problems.append(f"{script} check failed:\n{(result.stdout + result.stderr).strip()[-1500:]}")
    with tempfile.TemporaryDirectory(prefix="rename-validate-") as home:
        env = dict(os.environ, HOME=home, CLAUDE_CONFIG_DIR=f"{home}/.claude", CODEX_HOME=f"{home}/.codex")
        Path(home, ".claude").mkdir()
        Path(home, ".codex").mkdir()
        for target in claude_targets:
            if not claude_cli:
                problems.append(f"claude not found: run `claude plugin validate --strict {target}` by hand")
                continue
            result = run([claude_cli, "plugin", "validate", "--strict", target], root, env)
            ok = result.returncode == 0
            lines.append(f"  {'ok ' if ok else 'FAIL'}  claude plugin validate --strict {target}")
            if not ok:
                detail = (result.stdout + result.stderr).strip()[-1500:]
                problems.append(f"claude plugin validate --strict {target}:\n{detail}")
        if codex_ids and not codex_cli:
            problems.append(
                "codex not found: run `codex plugin marketplace add <repo>` and `codex plugin list` by hand"
            )
        elif codex_ids:
            added = run([codex_cli, "plugin", "marketplace", "add", str(root)], Path(home), env)
            listed = run([codex_cli, "plugin", "list"], Path(home), env)
            missing = [i for i in codex_ids if not re.search(rf"(^|\s){re.escape(i)}\s", listed.stdout, re.M)]
            ok = added.returncode == 0 and listed.returncode == 0 and not missing
            lines.append(
                f"  {'ok ' if ok else 'FAIL'}  codex plugin marketplace add + list: {', '.join(codex_ids)}"
            )
            if not ok:
                detail = (added.stdout + added.stderr + listed.stdout + listed.stderr).strip()[-1500:]
                problems.append(f"codex does not list {missing or codex_ids}:\n{detail}")
    return lines, problems


# ------------------------------------------------------------------------------ applying


def check_destinations(root: Path, plan: Plan, clear: bool = False) -> list[str]:
    """Refuse a move onto something that exists. A destination holding only files git ignores
    (``__pycache__`` left behind by switching from a renamed branch) is stale: with `clear`
    it is removed. Returns the stale destinations."""
    stale = []
    for src, dst, _ in plan.moves:
        path = root / dst
        if not os.path.lexists(path):
            continue
        owned = path.is_dir() and not path.is_symlink()
        if owned:
            owned = not git(root, "ls-files", "--", dst).strip()
            owned = owned and not git(root, "ls-files", "--others", "--exclude-standard", "--", dst).strip()
        if not owned:
            raise Refused(f"cannot move {src}: {dst} already exists")
        stale.append(dst)
        if clear:
            shutil.rmtree(path)
    return stale


def run_delegates(root: Path, plan: Plan, python: str, dry_run: bool) -> list[str]:
    """Let self-renaming packages go first. Returns problems."""
    problems = []
    for delegate in plan.delegates:
        cmd = [python, delegate.script, *delegate.rename_args, *(["--dry-run"] if dry_run else [])]
        result = run(cmd, root)
        print(f"$ python3 {shlex.join(cmd[1:])}")
        print(
            "\n".join(f"  | {line}" for line in (result.stdout + result.stderr).rstrip().splitlines()[-25:])
        )
        if result.returncode and not dry_run:
            problems.append(
                f"{delegate.script} rename exited {result.returncode}; its check runs again at the end"
            )
    return problems


def apply(
    root: Path, plan: Plan, python: str, policy: dict[str, Any], skip_lock: bool, skip_tools: bool
) -> list[str]:
    """Perform the plan (delegates have already run). Returns what needs the operator's attention."""
    problems: list[str] = []
    check_destinations(root, plan)
    for src, dst, _ in plan.moves:
        (root / dst).parent.mkdir(parents=True, exist_ok=True)
        git(root, "mv", src, dst)
        parent = (root / src).parent
        while parent != root and parent.is_dir() and not any(parent.iterdir()):
            parent.rmdir()
            parent = parent.parent
    python_files = []
    for change in plan.edited:
        (root / change.target).write_bytes(change.new_text.encode("utf-8"))
        if change.target.endswith(".py"):
            python_files.append(change.target)

    if not skip_tools:
        env = python_env(root)
        for module in plan.regenerators:
            wrote = run([python, "-m", module, "--write"], root, env)
            check = run([python, "-m", module], root, env)
            print(
                f"regenerated: python -m {module} --write"
                + (f"\n{wrote.stdout.rstrip()}" if wrote.stdout.strip() else "")
            )
            if wrote.returncode or check.returncode:
                problems.append(
                    f"python -m {module} --write: {wrote.stderr.strip()[-1500:]}{check.stdout.strip()}"
                )
        for path in plan.pins:
            module = path.removesuffix(".py").replace("/", ".")
            result = run([python, "-c", PIN_SNIPPET, module, json.dumps(policy["pins"][path])], root, env)
            if result.returncode:
                problems.append(f"could not recompute the pins in {path}: {result.stderr.strip()[-1500:]}")
                continue
            note = f"for {plan.new.display} by scripts/rename_product.py; confirm via Codex hooks/list."
            text = (root / path).read_text(encoding="utf-8")
            updated = rewrite_pins(text, json.loads(result.stdout), note)
            if updated != text:
                (root / path).write_text(updated, encoding="utf-8")
                print(f"re-pinned: {path}")
                python_files.append(path)
        venv_ruff = root / ".venv" / "bin" / "ruff"
        ruff = str(venv_ruff) if venv_ruff.exists() else shutil.which("ruff")
        existing = [p for p in dict.fromkeys(python_files) if (root / p).exists()]
        if ruff and existing:
            fixed = run([ruff, "check", "--select", "I", "--fix", "--quiet", *existing], root)
            if fixed.returncode:
                problems.append(f"ruff could not sort imports: {fixed.stdout.strip()}{fixed.stderr.strip()}")
        elif existing:
            problems.append("ruff not found: run `ruff check --select I --fix src tests` before committing")
    if not skip_lock:
        for path, commands in plan.lockfiles.items():
            for command in commands:
                if shutil.which(command[0]) and run(command, root).returncode == 0:
                    print(f"locked: {' '.join(command)}")
                    break
            else:
                problems.append(
                    f"{path} was not regenerated: run `uv lock` (it still names the old distribution)"
                )
    else:
        problems += [f"{path} was not regenerated (--skip-lock): run `uv lock`" for path in plan.lockfiles]
    return problems


def stage(root: Path, untracked_before: list[str]) -> None:
    git(root, "add", "-u")
    before = set(untracked_before)
    new = [p for p in tree_state(root)[1] if p not in before]
    if new:
        git(root, "add", "--", *new)


def verification(old: Forms, new: Forms, regenerators: list[str], previously: str | None) -> str:
    test = '.venv/bin/pytest -o addopts="" -q -p no:warnings'
    args = f"--from {old.display} --to {new.display}" + (f" --previously {previously}" if previously else "")
    return "\n".join(
        [
            "Verify:",
            "  uv sync --all-extras",
            f'  {new.upper}_HOME="$(mktemp -d)" {test}',
            f'  {old.upper}_HOME="$(mktemp -d)" {test}   # settings under the former name still work',
            "  .venv/bin/ruff check src tests scripts/rename_product.py",
            *[
                f"  .venv/bin/python -m {m}   # prints nothing, exits 0: generated files are current"
                for m in regenerators
            ],
            f"  python3 scripts/rename_product.py {args} --validate",
            f"  python3 scripts/rename_product.py {args} --audit",
            "  git diff --cached -M --stat; git diff --cached -M",
        ]
    )


# ------------------------------------------------------------------------------ main


def repo_root(start: Path) -> Path:
    proc = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"], cwd=start, capture_output=True, text=True, check=False
    )
    if proc.returncode:
        raise Refused(f"{start} is not inside a git repository")
    return Path(proc.stdout.strip())


def reserved_names(files: list[str]) -> set[str]:
    """Top-level names a new package name must not collide with."""
    names = {p.split("/", 1)[0].split(".", 1)[0].lower() for p in files}
    for base in ("src/", "tests/"):
        names |= {
            p[len(base) :].split("/", 1)[0].split(".", 1)[0].lower() for p in files if p.startswith(base)
        }
    return names


def clashes(texts: dict[str, str], kinds: dict[str, str], new: Forms) -> tuple[list[str], list[str]]:
    """Tracked files that already use the new name, outside the rename's own files:
    (Python sources, where it would collide with an identifier; everything else)."""
    in_use = loose_pattern(new)
    found = sorted(
        path
        for path, kind in kinds.items()
        if kind != "excluded" and (in_use.search(path) or (path in texts and in_use.search(texts[path])))
    )
    return [p for p in found if p.endswith(".py")], [p for p in found if not p.endswith(".py")]


def main(argv: list[str] | None = None, policy: dict[str, Any] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], epilog="See docs/RENAME.md.")
    parser.add_argument("--from", dest="old", required=True, help="the current name, e.g. AgentGuard")
    parser.add_argument("--to", dest="new", required=True, help="the new name, e.g. Truthstone")
    parser.add_argument("--lower", help="override the new lowercase form (package, commands)")
    parser.add_argument("--upper", help="override the new UPPER form (environment variables)")
    parser.add_argument("--kebab", help="override the new kebab-case form")
    parser.add_argument("--previously", help="name in 'New (previously named NAME)' (default: --from)")
    parser.add_argument("--no-previously", action="store_true", help="skip the first-mention convention")
    parser.add_argument("--dry-run", action="store_true", help="print the plan and change nothing")
    parser.add_argument("--audit", action="store_true", help="classify what is left of the old name")
    parser.add_argument("--validate", action="store_true", help="run the plugin validators on this tree")
    parser.add_argument("--json", action="store_true", help="with --dry-run: print the plan as JSON")
    parser.add_argument("--verbose", action="store_true", help="also list every distinct token rewrite")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent, help="the repository")
    parser.add_argument("--python", help="interpreter for generators and pins (default: .venv/bin/python)")
    parser.add_argument(
        "--claude", default=shutil.which("claude"), help="the Claude Code CLI, for validation"
    )
    parser.add_argument("--codex", default=shutil.which("codex"), help="the Codex CLI, for validation")
    parser.add_argument("--allow-untracked", action="store_true", help="run although untracked files exist")
    parser.add_argument("--force", action="store_true", help="run although Python sources use the new name")
    parser.add_argument("--skip-lock", action="store_true", help="do not run uv lock (say so instead)")
    parser.add_argument("--skip-tools", action="store_true", help="no generators, pins, ruff or validators")
    args = parser.parse_args(argv)
    policy = policy or DEFAULT_POLICY

    try:
        root = repo_root(args.root)
        old = derive_forms(args.old)
        new = derive_forms(args.new, lower=args.lower, upper=args.upper, kebab=args.kebab)
        previously = None if args.no_previously else (args.previously or old.display)
        python = args.python or default_python(root)
        if args.audit:
            report = audit(root, old, new, policy)
            print(render_audit(report, old))
            return EXIT_OK if report.clean else EXIT_ATTENTION
        files = tracked_files(root)
        if args.validate:
            lines, problems = validate_plugins(root, python, policy, args.claude, args.codex)
            print("Plugin validators:\n" + "\n".join(lines or ["  (none found)"]))
            if problems:
                print("\nProblems:\n" + "\n".join(f"  - {p}" for p in problems))
            return EXIT_ATTENTION if problems else EXIT_OK
        # The new name may already be a top-level name from an earlier run of this rename; the
        # clash check below tells that apart from a name genuinely in use.
        errors = validate_names(old, new, reserved_names(files) - {old.lower, new.lower})
        if errors:
            raise Refused("\n".join(errors))
        changed, untracked = tree_state(root)
        if not args.dry_run and (changed or (untracked and not args.allow_untracked)):
            listing = "\n".join(
                f"  {p}" for p in (changed + ([] if args.allow_untracked else untracked))[:20]
            )
            raise Refused(f"the working tree is not clean; commit or stash first:\n{listing}")
        kinds, texts = read_tree(root, files, policy)
        code, elsewhere = clashes(texts, kinds, new) if not prior_rename(texts, old, new) else ([], [])
        if code and not args.force:
            raise Refused(
                f"{new.display} already occurs in Python sources, and not from an earlier run of this "
                "rename, so it may collide with an identifier (pass --force to rename anyway):\n"
                + "\n".join(f"  {p}" for p in code[:20])
            )
        plan = build_plan(root, files, old, new, policy, previously)
        if code or elsewhere:
            plan.warnings.append(
                f"{new.display} already occurs before the rename (check that it is meant to): "
                + ", ".join(code + elsewhere)
            )
        if args.dry_run:
            if changed or untracked:
                print("note: the working tree is not clean; a real run would refuse\n", file=sys.stderr)
            if args.json:
                print(json.dumps(plan.to_json(), indent=2))
                return EXIT_OK
            if plan.delegates:
                print("Delegated renames, as their own tools describe them (they run first):")
                run_delegates(root, plan, python, dry_run=True)
                print()
            print(render_plan(plan, args.verbose))
            if not plan.has_changes:
                print(f"\nNothing to do: {old.display} is already renamed to {new.display}.")
            return EXIT_OK
        if not plan.has_changes:
            print(f"Nothing to do: {old.display} is already renamed to {new.display}.")
            return EXIT_OK
        problems = []
        # Before anything changes: a refusal from here on would leave a half-renamed tree.
        for stale in check_destinations(root, plan, clear=True):
            print(f"removed {stale}: it held only files git ignores (left by another branch)")
        delegates = plan.delegates
        if delegates:
            problems += run_delegates(root, plan, python, dry_run=False)
            warnings = plan.warnings
            plan = build_plan(root, tracked_files(root), old, new, policy, previously)  # what they left
            plan.delegates = delegates
            plan.warnings = list(dict.fromkeys(warnings + plan.warnings))
        print(render_plan(plan, args.verbose))
        print("\nApplying...")
        problems += apply(root, plan, python, policy, args.skip_lock, args.skip_tools)
        if not args.skip_tools:
            lines, more = validate_plugins(root, python, policy, args.claude, args.codex)
            print("\nPlugin validators:\n" + "\n".join(lines or ["  (none found)"]))
            problems += more
        stage(root, untracked)
        report = audit(root, old, new, policy)
        print("\n" + render_audit(report, old))
        if plan.warnings:
            print("\nWarnings:\n" + "\n".join(f"  - {w}" for w in plan.warnings))
        if problems:
            print("\nNeeds attention:\n" + "\n".join(f"  - {p}" for p in problems))
        print(
            f"\nStaged: {len(plan.moves)} move(s), {len(plan.edited)} file(s) edited. Nothing is committed."
        )
        print(verification(old, new, plan.regenerators, previously))
        return EXIT_ATTENTION if problems or not report.clean else EXIT_OK
    except Refused as refusal:
        print(f"refused: {refusal}", file=sys.stderr)
        return EXIT_REFUSED


if __name__ == "__main__":
    sys.exit(main())
