# ------------------------------------------------------------------------------ audit


@dataclass
class Audit:
    classes: Counter = field(default_factory=Counter)
    unexpected: list[str] = field(default_factory=list)
    env_gaps: list[str] = field(default_factory=list)

    @property
    def clean(self) -> bool:
        return not self.unexpected and not self.env_gaps


def audit(root: Path, old: Forms, new: Forms, policy: dict[str, Any]) -> Audit:
    """Classify every remaining spelling of the old name; find settings read without fallbacks."""
    pairs = replacement_pairs(old, new)
    pattern = spelling_pattern(pairs)
    loose = loose_pattern(old)
    files = tracked_files(root)
    kinds, texts = read_tree(root, files, policy)
    report = Audit()
    kept = [p for p in files if kinds[p] in ("historical", "excluded") and loose.search(p)]
    literals = kept_path_literals(kept, loose)
    for path in files:
        if kinds[path] == "binary" and loose.search(path):
            report.classes["binary file (name kept)"] += 1
        elif kinds[path] == "excluded" and (root / path).is_file():
            data = (root / path).read_bytes()
            if not is_binary(data):
                texts[path] = data.decode("utf-8")  # counted below, never rewritten
    for path, text in texts.items():
        hits = list(loose.finditer(text))
        if not hits:
            continue
        if kinds[path] == "excluded":
            report.classes["rename tooling (excluded)"] += len(hits)
            continue
        if kinds[path] == "historical":
            report.classes["historical record"] += len(hits)
            continue
        keep = merge_spans(keep_spans(text))
        refs = merge_spans(literal_spans(text, literals))
        previously = merge_spans(pattern_spans(text, PREVIOUSLY))
        titles = policy.get("historical_sections", {}).get(path, [])
        sections = merge_spans([(s, e) for s, _, e in markdown_sections(text, titles)])
        present = {line.strip() for line in text.splitlines()}
        for hit in hits:
            start, end = hit.span()
            line_start = text.rfind("\n", 0, start) + 1
            line_end = text.find("\n", start)
            line = text[line_start : len(text) if line_end == -1 else line_end]
            if overlaps(keep, start, end):
                report.classes["compatibility (keep block)"] += 1
            elif overlaps(previously, start, end):
                report.classes["prose: (previously named …)"] += 1
            elif overlaps(refs, start, end):
                report.classes["reference to a kept path"] += 1
            elif overlaps(sections, start, end):
                report.classes["historical record (section)"] += 1
            elif path.endswith(".gitignore") and rename_text(line, pattern, pairs).strip() in present:
                report.classes["compatibility (.gitignore)"] += 1
            else:
                report.classes["UNEXPECTED"] += 1
                report.unexpected.append(f"{path}:{text.count(chr(10), 0, start) + 1}: {line.strip()[:140]}")
    for path in kinds:
        if kinds[path] == "lockfile" and path in texts and loose.search(texts[path]):
            report.unexpected.append(f"{path}: still names {old.display} — run uv lock")
    report.env_gaps = env_gaps(texts, kinds, new)
    return report


def env_gaps(texts: dict[str, str], kinds: dict[str, str], new: Forms) -> list[str]:
    """Places that read a ``NEW_*`` setting without its former-name fallback."""
    prefix = re.escape(new.upper) + "_"
    gaps = []
    for path, text in texts.items():
        if kinds[path] != "living":
            continue
        if path.endswith(".py") and not path.startswith("tests/"):
            for number, line in enumerate(text.splitlines(), 1):
                literal = re.search(rf"[\"']{prefix}[A-Z0-9_]+[\"']", line)
                if literal and ENV_CONTEXT.search(line) and "names." not in line:
                    gaps.append(f"{path}:{number}: {line.strip()[:140]}")
        elif path.endswith(".sh"):
            keep = keep_spans(text)
            covered = {k for s, e in keep for k in re.findall(rf"\b{prefix}([A-Z0-9_]+)=\$", text[s:e])}
            for number, line in enumerate(blank_out(text, keep).splitlines(), 1):
                if line.lstrip().startswith("#"):
                    continue
                for key in re.findall(rf"\$\{{?{prefix}([A-Z0-9_]+)", line):
                    if key not in covered:
                        gaps.append(f"{path}:{number}: ${new.upper}_{key} has no former-name fallback")
    return sorted(set(gaps))


def render_audit(report: Audit, old: Forms) -> str:
    out = [f"What is left of {old.display}, by reason:"]
    out += [
        f"  {name:<34} {count:>5}"
        for name, count in sorted(report.classes.items(), key=lambda kv: (-kv[1], kv[0]))
    ]
    if not report.classes:
        out.append("  (nothing)")
    if report.unexpected:
        out.append("\nUNEXPECTED: review each one (a gap in the rename, or a policy to extend):")
        out += [f"  {u}" for u in report.unexpected]
    if report.env_gaps:
        out.append("\nSettings read without the former-name fallback (route Python through names.env;")
        out.append("re-run this tool for hand-written shell scripts):")
        out += [f"  {g}" for g in report.env_gaps]
    return "\n".join(out)


