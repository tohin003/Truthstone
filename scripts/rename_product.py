def rewrite_gitignore(text: str, pattern: re.Pattern[str], pairs: dict[str, str]) -> tuple[str, int]:
    """Rename ignore patterns, keeping the old ones: existing checkouts still hold that state."""
    lines = text.splitlines(keepends=True)
    present = {line.strip() for line in lines}
    out, count = [], 0
    for line in lines:
        if not pattern.search(line):
            out.append(line)
            continue
        renamed = rename_text(line, pattern, pairs)
        if line.lstrip().startswith("#"):
            out.append(renamed)
            count += 1
            continue
        if renamed.strip() not in present:
            out.append(renamed if renamed.endswith("\n") else renamed + "\n")
            present.add(renamed.strip())
            count += 1
        out.append(line if line.endswith("\n") else line + "\n")
    return "".join(out), count


def historical_note(new: Forms) -> str:
    return (
        f"> **Note:** the product has since been renamed **{new.display}**. What follows "
        f"predates the rename and is kept as written. {NOTE_MARK}"
    )


def upsert_note(text: str, note: str, after: int | None = None) -> str:
    """Put `note` below the heading line ending at offset `after`, or below the first H1."""
    lines = text.splitlines(keepends=True)
    if after is None:
        index = next((i + 1 for i, line in enumerate(lines[:5]) if line.startswith("# ")), 0)
    else:
        index = len(text[:after].splitlines(keepends=True))
    for j in range(index, min(index + 4, len(lines))):
        if NOTE_MARK in lines[j]:
            lines[j] = note + ("\n" if lines[j].endswith("\n") else "")
            return "".join(lines)
    block = ["\n", note + "\n"] if index else [note + "\n", "\n"]
    if index and not lines[index - 1].endswith("\n"):
        lines[index - 1] += "\n"
    return "".join(lines[:index] + block + lines[index:])


def registry_block(text: str) -> tuple[list[str], int, int] | None:
    lines = text.splitlines(keepends=True)
    begin = next((i for i, line in enumerate(lines) if REGISTRY.search(line)), None)
    if begin is None:
        return None
    end = next((i for i in range(begin + 1, len(lines)) if KEEP.search(lines[i])), None)
    if end is None:
        raise Refused("a former-names registry block has no keep-end line")
    return lines, begin, end


def registry_node(block: str) -> ast.AnnAssign | ast.Assign:
    nodes = [n for n in ast.parse(block).body if isinstance(n, ast.AnnAssign | ast.Assign)]
    if len(nodes) != 1 or nodes[0].value is None:
        raise Refused("a former-names registry must hold exactly one assignment")
    return nodes[0]


def registry_entries(text: str) -> list[tuple[str, ...]]:
    found = registry_block(text)
    if found is None:
        return []
    lines, begin, end = found
    return [tuple(e) for e in ast.literal_eval(registry_node("".join(lines[begin + 1 : end])).value)]


def update_registry(text: str, old: Forms, new: Forms) -> tuple[str, bool]:
    """Record `old` as the newest former name (and never list the current name)."""
    found = registry_block(text)
    if found is None:
        raise Refused("no former-names registry in this file")
    lines, begin, end = found
    block = "".join(lines[begin + 1 : end])
    node = registry_node(block)
    entries = [tuple(e) for e in ast.literal_eval(node.value)]
    entry = (old.display, old.lower, old.upper)
    current = (new.display, new.lower, new.upper)
    updated = [entry, *(e for e in entries if e not in (entry, current))]
    if updated == entries:
        return text, False
    if isinstance(node, ast.AnnAssign):
        target = ast.get_source_segment(block, node.target)
        head = f"{target}: {ast.get_source_segment(block, node.annotation)}"
    else:
        head = " = ".join(ast.get_source_segment(block, t) or "" for t in node.targets)
    rendered = ["(" + ", ".join(json.dumps(s) for s in e) + ")" for e in updated]
    if len(rendered) == 1:
        code = f"{head} = ({rendered[0]},)\n"
    else:
        code = f"{head} = (\n" + "".join(f"    {r},\n" for r in rendered) + ")\n"
    block_lines = block.splitlines(keepends=True)
    new_block = [*block_lines[: node.lineno - 1], code, *block_lines[node.end_lineno :]]
    return "".join(lines[: begin + 1] + new_block + lines[end:]), True


def shell_fallbacks(text: str, old: Forms, new: Forms) -> tuple[str, bool]:
    """Give a hand-written shell script fallbacks for its settings under former names.

    For each ``$NEW_X`` the script reads, one line per former name, newest first:
    ``[ -n "${NEW_X:-}" ] || [ -z "${OLD_X+x}" ] || NEW_X=$OLD_X`` (the format of
    ``names.shell_fallbacks``: a non-empty current setting wins, and an unset former one
    leaves the current one unset). They sit in a keep block after the file's header comment;
    a block from an earlier rename is rebuilt with the whole chain. Generated scripts are
    skipped: their generator writes the same block itself.
    """
    lines = text.splitlines(keepends=True)
    if any("GENERATED" in line for line in lines[:5]):
        return text, False
    formers = [old.upper]
    body: list[str] = []
    block_at = None
    i = 0
    while i < len(lines):
        if not SHELL_BLOCK.search(lines[i]):
            body.append(lines[i])
            i += 1
            continue
        block_at = len(body)
        i += 1
        while i < len(lines) and not KEEP.search(lines[i]):
            formers += re.findall(r"\$\{([A-Z][A-Z0-9]*)_[A-Z0-9_]+[:+]", lines[i])
            i += 1
        i += 1  # the keep-end line
        if i < len(lines) and not lines[i].strip():
            i += 1  # and the blank line after the block
    chain = list(dict.fromkeys(p for p in formers if p != new.upper))
    keys = sorted(set(re.findall(rf"\$\{{?{re.escape(new.upper)}_([A-Z0-9_]+)", "".join(body))))
    block = []
    if keys and chain:
        block.append(
            f"# {PRAGMA} keep-begin former-settings (settings under a former product name still apply)\n"
        )
        for key in keys:
            current = f"{new.upper}_{key}"
            for prefix in chain:
                former = f"{prefix}_{key}"
                block.append(
                    f'[ -n "${{{current}:-}}" ] || [ -z "${{{former}+x}}" ] || {current}=${former}\n'
                )
        block += [f"# {PRAGMA} keep-end\n", "\n"]
    if block_at is None:
        # After the file's header comment and the blank line that ends it: later comment
        # blocks belong to the code below them.
        block_at = 0
        while block_at < len(body) and body[block_at].startswith("#"):
            block_at += 1
        if block_at < len(body) and not body[block_at].strip():
            block_at += 1
    result = "".join(body[:block_at] + block + body[block_at:])
    return result, result != text


def rewrite_pins(text: str, values: dict[str, Any], note: str) -> str:
    """Replace ``NAME = "..."`` and multi-line ``NAME = {...}`` constants; mark them."""
    lines = text.splitlines(keepends=True)
    out: list[str] = []
    i, marked = 0, False
    while i < len(lines):
        line = lines[i]
        if line.startswith(PIN_MARK):
            i += 1
            continue
        name = next((n for n in values if re.match(rf"{re.escape(n)}\s*=", line)), None)
        if name is None:
            out.append(line)
            i += 1
            continue
        if not marked:
            out.append(f"{PIN_MARK} {note}\n")
            marked = True
        value = values[name]
        if isinstance(value, dict):
            items = "".join(f"    {json.dumps(k)}: {json.dumps(v)},\n" for k, v in value.items())
            out.append(f"{name} = {{\n{items}}}\n")
            if line.rstrip().endswith("{"):
                while i < len(lines) and lines[i].rstrip() != "}":
                    i += 1
        else:
            out.append(f"{name} = {json.dumps(value)}\n")
        i += 1
    return "".join(out)


# ------------------------------------------------------------------------------ "previously named"


def previously_phrase(old_display: str) -> str:
    return f" (previously named {old_display})"


APOSTROPHES = "'\u2019"  # ASCII and typographic
BEFORE_NOT_PROSE = "_/-.@#$\\`<[(" + APOSTROPHES
AFTER_NOT_PROSE = "_/-@`\\])" + APOSTROPHES


def plain_mention(text: str, start: int, end: int) -> bool:
    """Whether the name at [start, end) stands on its own in prose.

    Not when it is part of a word, path, URL, identifier, possessive or compound proper
    name ("Truthstone Practices", "Truthstone-Bench", "Truthstone's"), or bracketed.
    """
    before = text[start - 1] if start else ""
    after = text[end : end + 1]
    if before and (before.isalnum() or before in BEFORE_NOT_PROSE):
        return False
    if after and (after.isalnum() or after in AFTER_NOT_PROSE):
        return False
    if after == "." and text[end + 1 : end + 2].isalnum():
        return False  # a dotted name
    return not (after == " " and text[end + 1 : end + 2].isupper())  # a compound proper name


def first_plain_mention(text: str, name: str, masked: list[Span]) -> int | None:
    """End offset of the first plain mention of `name` outside `masked`."""
    masked = merge_spans(masked)
    start = text.find(name)
    while start != -1:
        end = start + len(name)
        if not overlaps(masked, start, end) and plain_mention(text, start, end):
            return end
        start = text.find(name, end)
    return None


def markdown_masks(text: str, name: str) -> list[Span]:
    """Where a Markdown mention is not prose: code, comments, URLs, and headings that are
    more than the bare name (a title that *is* the name is the document's first mention)."""
    spans = keep_spans(text) + pattern_spans(text, URL) + pattern_spans(text, re.compile(r"<!--.*?-->", re.S))
    spans += pattern_spans(text, re.compile(r"\]\([^)]*\)"))  # link targets
    spans += pattern_spans(text, re.compile(r"(`+)(?!`)(?:(?!\n\n).)+?(?<!`)\1", re.S))  # inline code
    fenced_from = None
    for start, end, heading in markdown_lines(text):
        line = text[start:end]
        if re.match(r"\s*[>|]", line):  # quotes and tables reproduce text verbatim
            spans.append((start, end))
        if FENCE.match(line):
            if fenced_from is None:
                fenced_from = start
            else:
                spans.append((fenced_from, end))
                fenced_from = None
        elif fenced_from is None and heading and heading.group(2).strip("* ") != name:
            spans.append((start, end))
    if fenced_from is not None:
        spans.append((fenced_from, len(text)))
    if text.startswith("---\n"):  # front matter: only `description:` is prose
        close = text.find("\n---", 4)
        if close != -1:
            for match in re.finditer(r"^(?!description:).*$", text[: close + 4], re.M):
                spans.append(match.span())
    return spans


def annotate_markdown(text: str, new: Forms, old_display: str) -> tuple[str, bool]:
    if f"previously named {old_display}" in text:
        return text, False
    end = first_plain_mention(text, new.display, markdown_masks(text, new.display))
    if end is None:
        return text, False
    return text[:end] + previously_phrase(old_display) + text[end:], True


def annotate_json_fields(text: str, keys: list[str], new: Forms, old_display: str) -> tuple[str, int]:
    """Annotate the first plain mention inside every ``"key": "..."`` string, editing the raw
    text so the file's own formatting survives."""
    count = 0
    pattern = re.compile(r'"(' + "|".join(re.escape(k) for k in keys) + r')"\s*:\s*("(?:[^"\\]|\\.)*")')
    out, last = [], 0
    for match in pattern.finditer(text):
        raw = match.group(2)
        value = json.loads(raw)
        if not isinstance(value, str) or f"previously named {old_display}" in value:
            continue
        end = first_plain_mention(value, new.display, pattern_spans(value, URL))
        if end is None:
            continue
        nth = value[:end].count(new.display)
        position = match.start(2) + nth_end(raw, new.display, nth)
        out += [text[last:position], previously_phrase(old_display)]
        last = position
        count += 1
    out.append(text[last:])
    return "".join(out), count


def nth_end(text: str, needle: str, nth: int) -> int:
    """End offset of the `nth` (1-based) occurrence of `needle` in `text`."""
    position = -1
    for _ in range(nth):
        position = text.find(needle, position + 1)
    return position + len(needle)


def annotate_python_constants(
    text: str, names_: list[str], new: Forms, old_display: str, max_line: int
) -> tuple[str, int, list[str]]:
    """Annotate the first plain mention inside string constants, re-wrapping a line that the
    phrase makes too long. Returns (text, annotations, problems)."""
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return text, 0, []
    edits: list[int] = []
    for node in tree.body:
        targets = (
            node.targets
            if isinstance(node, ast.Assign)
            else [node.target]
            if isinstance(node, ast.AnnAssign)
            else []
        )
        if not any(isinstance(t, ast.Name) and t.id in names_ for t in targets):
            continue
        value = getattr(node, "value", None)
        if not (isinstance(value, ast.Constant) and isinstance(value.value, str)):
            continue
        if f"previously named {old_display}" in value.value:
            continue
        end = first_plain_mention(value.value, new.display, pattern_spans(value.value, URL))
        if end is None:
            continue
        nth = value.value[:end].count(new.display)
        start = char_offset(text, value.lineno, value.col_offset)
        stop = char_offset(text, value.end_lineno, value.end_col_offset)
        edits.append(start + nth_end(text[start:stop], new.display, nth))
    problems: list[str] = []
    for position in sorted(edits, reverse=True):
        text = text[:position] + previously_phrase(old_display) + text[position:]
        text, problem = rewrap_literal_line(text, position, max_line)
        if problem:
            problems.append(problem)
    return text, len(edits), problems


def char_offset(text: str, lineno: int, byte_col: int) -> int:
    """The character offset of an AST position (line 1-based, column in UTF-8 bytes)."""
    lines = text.splitlines(keepends=True)
    before = sum(len(line) for line in lines[: lineno - 1])
    return before + len(lines[lineno - 1].encode("utf-8")[:byte_col].decode("utf-8"))


LITERAL_LINE = re.compile(r'(\s*)"((?:[^"\\]|\\.)*)"(\s*[,)]?\s*)')


def rewrap_literal_line(text: str, position: int, max_line: int) -> tuple[str, str | None]:
    """Re-wrap the string-literal line holding `position` if it is now too long.

    The overflow moves into the next literal lines of the same implicit concatenation, word by
    word, until it fits; lines after that are left exactly as they were.
    """
    lines = text.splitlines(keepends=True)
    index = len(text[:position].splitlines(keepends=True)) - 1
    first = LITERAL_LINE.fullmatch(lines[index].rstrip("\n"))
    if len(lines[index].rstrip("\n")) <= max_line:
        return text, None
    if not first:
        return text, f"a line over {max_line} characters needs wrapping by hand: {lines[index].strip()[:80]}"
    indent = first.group(1)
    limit = max_line - len(indent) - 2
    carry, out, i = "", [], index
    while True:
        match = LITERAL_LINE.fullmatch(lines[i].rstrip("\n")) if i < len(lines) else None
        if match is None or match.group(1) != indent:  # ran out of literal lines: the carry stands alone
            out.append(f'{indent}"{carry}"\n')
            break
        body, tail = carry + match.group(2), match.group(3)
        if len(body) <= limit:
            out.append(f'{indent}"{body}"{tail}\n')
            i += 1
            break
        cut = body.rfind(" ", 0, limit)
        if cut <= 0:
            return (
                text,
                f"a line over {max_line} characters needs wrapping by hand: {lines[index].strip()[:80]}",
            )
        out.append(f'{indent}"{body[: cut + 1]}"\n')
        carry = body[cut + 1 :]
        if tail.strip():  # the concatenation ends here: the carry gets its own last line
            out.append(f'{indent}"{carry}"{tail}\n')
            i += 1
            break
        i += 1
    return "".join(lines[:index] + out + lines[i:]), None


def renamed_note(text: str, old: Forms, new: Forms) -> str:
    """The README's "Renamed from Old" section: what keeps working after the rename."""
    found = list(dict.fromkeys(re.findall(rf"\b{re.escape(new.upper)}_([A-Z][A-Z0-9_]*)\b", text)))[:3]
    examples = ", ".join(f"`{old.upper}_{key}`" for key in found) or f"`{old.upper}_HOME`"
    return (
        f"<!-- {PRAGMA} keep-begin renamed-note -->\n"
        f"## Renamed from {old.display}\n\n"
        f"{new.display} was previously named {old.display}. Installs made under the old name keep\n"
        "working:\n\n"
        f"- **Settings.** Every `{old.upper}_*` environment variable still applies when its\n"
        f"  `{new.upper}_*` counterpart is unset ({examples}).\n"
        f"- **Data.** An existing `~/.{old.lower}` directory stays in use until `~/.{new.lower}`\n"
        f"  exists; `{new.lower} doctor` prints the command that moves it.\n"
        f"- **Hooks.** Hooks written by `{old.lower} install` are recognised:\n"
        f"  `{new.lower} install` replaces them and `{new.lower} uninstall` removes them, so nothing\n"
        "  runs twice.\n"
        "- **Names.** The package, the commands and the plugins carry the new name\n"
        f"  (`{new.lower}`, `{new.lower}-hook`, ...). Remove a plugin installed under the old name\n"
        "  and add the new one.\n"
        f"<!-- {PRAGMA} keep-end -->\n\n"
    )


def upsert_renamed_note(text: str, old: Forms, new: Forms) -> tuple[str, bool]:
    note = renamed_note(text, old, new)
    lines = text.splitlines(keepends=True)
    begin = next((i for i, line in enumerate(lines) if NOTE_BLOCK.search(line)), None)
    if begin is not None:
        end = next((i for i in range(begin + 1, len(lines)) if KEEP.search(lines[i])), len(lines) - 1)
        stop = end + 1
        while stop < len(lines) and not lines[stop].strip():
            stop += 1
        updated = "".join(lines[:begin]) + note + "".join(lines[stop:])
        return updated, updated != text
    index = next(
        (i for i, (_, _, h) in enumerate(markdown_lines(text)) if h and len(h.group(1)) == 2), len(lines)
    )
    if index and lines[index - 1].strip():
        note = "\n" + note
    updated = "".join(lines[:index]) + note + "".join(lines[index:])
    return updated, True


