@dataclass
class FileChange:
    path: str
    target: str
    kind: str  # living | historical
    counts: Counter = field(default_factory=Counter)
    notes: list[str] = field(default_factory=list)
    new_text: str | None = None


@dataclass
class Plan:
    old: Forms
    new: Forms
    pairs: dict[str, str]
    previously: str | None = None
    targets: dict[str, str] = field(default_factory=dict)
    files: list[FileChange] = field(default_factory=list)
    moves: list[tuple[str, str, bool]] = field(default_factory=list)
    tokens: Counter = field(default_factory=Counter)
    historical: list[str] = field(default_factory=list)
    protected: list[str] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)
    unhandled: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    regenerators: list[str] = field(default_factory=list)
    delegates: list[Delegate] = field(default_factory=list)
    lockfiles: dict[str, list[list[str]]] = field(default_factory=dict)
    pins: list[str] = field(default_factory=list)
    registries: list[str] = field(default_factory=list)
    rerun: bool = False

    @property
    def edited(self) -> list[FileChange]:
        return [f for f in self.files if f.new_text is not None]

    @property
    def has_changes(self) -> bool:
        return bool(self.edited or self.moves or self.delegates)

    def by_class(self) -> tuple[Counter, Counter]:
        occurrences: Counter = Counter()
        files: Counter = Counter()
        for f in self.files:
            occurrences.update(f.counts)
            files.update(set(f.counts))
        return occurrences, files

    def to_json(self) -> dict[str, Any]:
        occurrences, files = self.by_class()
        return {
            "old": asdict(self.old),
            "new": asdict(self.new),
            "previously": self.previously,
            "rerun": self.rerun,
            "classes": {k: {"occurrences": v, "files": files[k]} for k, v in occurrences.items()},
            "files": {
                f.path: {"target": f.target, "counts": dict(f.counts), "notes": f.notes} for f in self.edited
            },
            "moves": [{"from": a, "to": b, "directory": d} for a, b, d in self.moves],
            "delegates": [
                {"script": d.script, "summary": d.summary, "args": d.rename_args} for d in self.delegates
            ],
            "historical": self.historical,
            "protected": self.protected,
            "skipped": self.skipped,
            "unhandled": self.unhandled,
            "warnings": self.warnings,
            "regenerators": self.regenerators,
            "lockfiles": list(self.lockfiles),
            "pins": self.pins,
            "registries": self.registries,
        }


def matches(path: str, patterns: list[str]) -> bool:
    return any(fnmatch.fnmatchcase(path, p) for p in patterns)


def matching_fields(path: str, table: dict[str, list[str]]) -> list[str]:
    return sorted(
        {key for pattern, keys in table.items() if fnmatch.fnmatchcase(path, pattern) for key in keys}
    )


def is_binary(data: bytes) -> bool:
    if b"\0" in data[:8192]:
        return True
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        return True
    return False


def read_tree(root: Path, files: list[str], policy: dict[str, Any]) -> tuple[dict[str, str], dict[str, str]]:
    """(kind of each tracked file, text of each text file)."""
    kinds: dict[str, str] = {}
    texts: dict[str, str] = {}
    for path in files:
        full = root / path
        if matches(path, policy.get("exclude", [])):
            kinds[path] = "excluded"
        elif path in policy.get("lockfiles", {}):
            kinds[path] = "lockfile"
        elif full.is_symlink() or not full.is_file():
            kinds[path] = "special"
        else:
            data = full.read_bytes()
            if is_binary(data):
                kinds[path] = "binary"
            else:
                texts[path] = data.decode("utf-8")
                kinds[path] = "historical" if matches(path, policy.get("historical", [])) else "living"
    return kinds, texts


def kept_path_literals(paths: list[str], pattern: re.Pattern[str]) -> list[str]:
    """Paths (and their file names) that keep the old name: references to them must too."""
    literals: set[str] = set()
    for path in paths:
        if not pattern.search(path):
            continue
        base = path.rsplit("/", 1)[-1]
        literals.update({path, base})
        stem = base.rsplit(".", 1)[0]
        if pattern.sub("", stem).strip(" -_—"):  # more than the bare name
            literals.add(stem)
    return sorted(literals, key=len, reverse=True)


def uncovered_lines(
    text: str, protected: list[Span], loose: re.Pattern[str], gitignore: bool
) -> Iterator[tuple[int, str]]:
    """Lines that still spell the old name somewhere the rewrite did not reach."""
    lines = text.splitlines()
    for number, line in enumerate(blank_out(text, protected).splitlines(), 1):
        if loose.search(line) and not (gitignore and not line.lstrip().startswith("#")):
            yield number, lines[number - 1].strip()


def ruff_line_length(root: Path) -> int:
    try:
        config = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
        return int(config["tool"]["ruff"]["line-length"])
    except (OSError, KeyError, ValueError, TypeError):
        return 88


def prior_rename(texts: dict[str, str], old: Forms, new: Forms) -> bool:
    """Whether this tree already shows this rename (so the new name may occur in it)."""
    phrase = f"previously named {old.display}"
    for text in texts.values():
        if phrase in text or (NOTE_MARK in text and new.display in text):
            return True
        if REGISTRY.search(text) and (old.display, old.lower, old.upper) in registry_entries(text):
            return True
    return False


def build_plan(
    root: Path, files: list[str], old: Forms, new: Forms, policy: dict[str, Any], previously: str | None
) -> Plan:
    pairs = replacement_pairs(old, new)
    pattern = spelling_pattern(pairs)
    loose = loose_pattern(old)
    plan = Plan(old, new, pairs, previously)
    kinds, texts = read_tree(root, files, policy)
    sections: dict[str, list[str]] = policy.get("historical_sections", {})
    prose: dict[str, Any] = policy.get("previously", {})
    max_line = ruff_line_length(root)

    kept = [p for p, k in kinds.items() if k in ("historical", "excluded", "binary", "special")]
    plan.protected = kept_path_literals([p for p in kept if kinds[p] != "binary"], pattern)
    for path in kept:
        if kinds[path] in ("binary", "special") and pattern.search(path.rsplit("/", 1)[-1]):
            plan.skipped.append(f"{path} ({kinds[path]}: kept as is; rebuild or rename it by hand)")

    plan.registries = sorted(p for p, t in texts.items() if kinds[p] == "living" and REGISTRY.search(t))
    entry = (old.display, old.lower, old.upper)
    plan.rerun = bool(plan.registries) and all(entry in registry_entries(texts[p]) for p in plan.registries)
    if not plan.registries:
        plan.warnings.append(
            "no former-names registry on this branch: the renamed code will honour old settings only "
            "once merged with a branch that has one (agentguard.names)"
        )
    plan.delegates, warnings = discover_delegates(root, texts, kinds, pattern, pairs)
    plan.warnings += warnings

    for path in files:
        if kinds[path] == "living":
            plan.targets[path] = rename_path(path, pattern, pairs)
        elif kinds[path] == "binary":
            plan.targets[path] = rename_path(path, pattern, pairs, keep_basename=True)
        else:
            plan.targets[path] = path
    plan.moves = plan_moves(plan.targets, lambda d: rename_path(d, pattern, pairs))

    for path in files:
        kind = kinds[path]
        if kind == "lockfile":
            plan.lockfiles[path] = policy["lockfiles"][path]
        if kind not in ("living", "historical"):
            continue
        text = texts[path]
        change = FileChange(path, plan.targets[path], kind)
        if kind == "historical":
            if loose.search(text) or pattern.search(path):
                plan.historical.append(path)
                marked = policy.get("mark_historical") and path.endswith(".md")
                noted = upsert_note(text, historical_note(new)) if marked else text
                if noted != text:
                    change.new_text = noted
                    change.counts["historical note"] += 1
                    change.notes.append("historical note")
            if change.new_text is not None:
                plan.files.append(change)
            continue

        titles = sections.get(path, [])
        if path.rsplit("/", 1)[-1] == ".gitignore":
            new_text, count = rewrite_gitignore(text, pattern, pairs)
            if count:
                change.counts["data dir"] += count
                change.notes.append("former ignore patterns kept")
        else:
            protected = protected_spans(text, plan.protected, titles)
            new_text, hits = substitute(text, path, pattern, pairs, protected, old)
            for hit in hits:
                change.counts[hit.kind] += 1
                plan.tokens[(hit.token, rename_text(hit.token, pattern, pairs))] += 1
        # Sections are masked, so they are found again unchanged; last first, as notes shift text.
        for start, end, stop in reversed(markdown_sections(new_text, titles)):
            if loose.search(new_text[end:stop]):
                plan.historical.append(f"{path} § {new_text[start:end].strip()}")
                if not policy.get("mark_historical"):
                    continue
                noted = upsert_note(new_text, historical_note(new), after=end)
                if noted != new_text:
                    new_text = noted
                    change.counts["historical note"] += 1
                    change.notes.append("historical note on a section")
        if path in plan.registries:
            new_text, recorded = update_registry(new_text, old, new)
            if recorded:
                change.counts["former-names registry"] += 1
                change.notes.append(f"records {old.display} as a former name")
        if previously:
            new_text = annotate(new_text, plan, change, prose, max_line)
        if path.endswith(".sh"):
            new_text, added = shell_fallbacks(new_text, old, new)
            if added:
                change.counts["shell fallbacks"] += 1
                change.notes.append("fallbacks for settings under the former name")
        still = protected_spans(new_text, plan.protected, titles)
        for number, line in uncovered_lines(new_text, still, loose, path.endswith(".gitignore")):
            plan.unhandled.append(f"{plan.targets[path]}:{number}: {line[:140]}")
        if new_text != text:
            change.new_text = new_text
        if change.new_text is not None or change.path != change.target:
            plan.files.append(change)

    living = {p: t for p, t in texts.items() if kinds[p] == "living"}
    plan.regenerators = discover_regenerators(living, pattern, pairs)
    plan.pins = [p for p in policy.get("pins", {}) if p in kinds]
    return plan


def annotate(text: str, plan: Plan, change: FileChange, prose: dict[str, Any], max_line: int) -> str:
    """Apply the "New (previously named Old)" convention to one file, if it is a target.

    Targets are matched on the file's *new* path, so the same policy works before and after.
    """
    path, old_display = change.target, plan.previously or plan.old.display
    if matches(path, prose.get("markdown", [])):
        text, done = annotate_markdown(text, plan.new, old_display)
        if done:
            change.counts["previously named"] += 1
            change.notes.append("first mention: previously named")
    keys = matching_fields(path, prose.get("json_fields", {}))
    if keys:
        text, count = annotate_json_fields(text, keys, plan.new, old_display)
        if count:
            change.counts["previously named"] += count
            change.notes.append(f"first mention in {count} listing field(s): previously named")
    constants = matching_fields(path, prose.get("python_constants", {}))
    if constants:
        text, count, problems = annotate_python_constants(text, constants, plan.new, old_display, max_line)
        if count:
            change.counts["previously named"] += count
            change.notes.append(f"first mention in {count} constant(s): previously named")
        plan.warnings += [f"{path}: {p}" for p in problems]
    if matches(path, prose.get("renamed_note", [])):
        text, added = upsert_renamed_note(text, plan.old, plan.new)
        if added:
            change.counts["renamed note"] += 1
            change.notes.append(f"Renamed from {plan.old.display} section")
    return text


def discover_regenerators(
    texts: dict[str, str], pattern: re.Pattern[str], pairs: dict[str, str]
) -> list[str]:
    """Modules whose own documentation says ``python -m <module> --write`` regenerates files."""
    found = set()
    for path, text in texts.items():
        if path.endswith(".py"):
            for module in re.findall(r"python -m ([A-Za-z_][\w.]*) --write\b", text):
                found.add(rename_text(module, pattern, pairs))
    return sorted(found)


