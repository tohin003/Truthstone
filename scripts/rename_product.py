#!/usr/bin/env python3
"""Rename the product in one mechanical, reviewable, idempotent pass.

    python3 scripts/rename_product.py --from AgentGuard --to Truthstone --dry-run
    python3 scripts/rename_product.py --from AgentGuard --to Truthstone
    python3 scripts/rename_product.py --from AgentGuard --to Truthstone --audit
    python3 scripts/rename_product.py --from AgentGuard --to Truthstone --validate

The first prints the plan and changes nothing. The second performs it and stages the result
for review (``git diff --cached -M``). ``--audit`` classifies every remaining spelling of the
old name; ``--validate`` runs the plugin validators. ``docs/RENAME.md`` explains each decision.

A real run, in order:

1. refuses a dirty tree, an invalid new name, or one the repository already uses for
   something else;
2. lets packages that rename themselves do so first (a script that documents
   ``python3 <script> rename --slug NEW --display ...``, such as the skills companion);
3. rewrites every spelling of the old name (AgentGuard, agentguard, AGENTGUARD, and the
   kebab, snake and spaced forms) in tracked text files, except historical records (kept as
   written, with a one-line note), the rename's own files, ``(previously named ...)``
   phrases, and spans marked with the ``rename-tool: keep`` pragma;
4. moves every tracked path that contains the old name, with ``git mv``;
5. records the old name in every former-names registry (a ``former-names`` keep block):
   those entries keep old environment variables, the old data directory and old hook
   entries working;
6. writes the first plain mention of the new name in each user-facing document as
   "New (previously named Old)", and adds a "Renamed from Old" note to the README;
7. keeps the old per-workspace state directory ignored, and gives hand-written shell scripts
   fallbacks for settings under the old name;
8. runs the repository's generators (every ``python -m <module> --write`` its sources
   document), re-pins pinned hashes, re-sorts imports, regenerates uv.lock, and runs the
   plugin validators (``claude plugin validate --strict``, ``codex plugin list``, the
   companion's ``check``);
9. stages everything, audits what is left, and prints the commands that verify it.

Deterministic: the result depends only on the tree and the arguments, so the same command
can be run on every branch before merging. On an already renamed tree it does nothing; on a
branch that gained code under the old name it renames just that code. Stdlib only, so any
Python 3.11+ runs it; generators and pins run under the repository's own interpreter
(``.venv/bin/python`` unless ``--python`` says otherwise).
"""

