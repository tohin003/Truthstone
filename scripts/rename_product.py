class Refused(Exception):
    """The rename must not run (dirty tree, bad name, ...). Nothing has been changed."""


# ------------------------------------------------------------------------------ names

_WORD = re.compile(r"[A-Z]+(?=[A-Z][a-z0-9])|[A-Z]?[a-z0-9]+|[A-Z]+")


@dataclass(frozen=True)
class Forms:
    """Every spelling of one product name."""

    display: str  # AgentGuard    prose, headers, URLs
    lower: str  # agentguard    package, distribution, commands, paths
    upper: str  # AGENTGUARD    environment variables
    kebab: str  # agent-guard
    snake: str  # agent_guard
    upper_snake: str  # AGENT_GUARD
    spaced: str  # Agent Guard
    title: str  # Agentguard    sentence case; rewritten as the new display form


def split_words(name: str) -> list[str]:
    words = _WORD.findall(name)
    if not name or "".join(words) != name:
        raise Refused(f"{name!r} is not a product name: use letters and digits, e.g. Truthstone")
    return words


def derive_forms(
    name: str, lower: str | None = None, upper: str | None = None, kebab: str | None = None
) -> Forms:
    words = split_words(name)
    return Forms(
        display=name,
        lower=lower or name.lower(),
        upper=upper or name.upper(),
        kebab=kebab or "-".join(w.lower() for w in words),
        snake="_".join(w.lower() for w in words),
        upper_snake="_".join(w.upper() for w in words),
        spaced=" ".join(words),
        title=name[:1].upper() + name[1:].lower(),
    )


def replacement_pairs(old: Forms, new: Forms) -> dict[str, str]:
    """Old spelling -> new spelling. The three primary forms win over the derived ones."""
    order = [
        ("display", "display"),
        ("lower", "lower"),
        ("upper", "upper"),
        ("kebab", "kebab"),
        ("snake", "snake"),
        ("upper_snake", "upper_snake"),
        ("spaced", "spaced"),
        ("title", "display"),
    ]
    pairs: dict[str, str] = {}
    for old_attr, new_attr in order:
        key = getattr(old, old_attr)
        if key and key not in pairs:
            pairs[key] = getattr(new, new_attr)
    return {k: v for k, v in pairs.items() if k != v}


def spelling_pattern(pairs: dict[str, str]) -> re.Pattern[str]:
    return re.compile("|".join(re.escape(k) for k in sorted(pairs, key=len, reverse=True)))


def loose_pattern(forms: Forms) -> re.Pattern[str]:
    """Any casing of the name, with or without separators: what a reader would call it."""
    return re.compile(r"[-_ ]?".join(re.escape(w) for w in split_words(forms.display)), re.IGNORECASE)


def validate_names(old: Forms, new: Forms, reserved: set[str]) -> list[str]:
    errors = []
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", new.display):
        errors.append(f"--to {new.display!r}: letters and digits only, starting with a letter")
    if not new.lower.isidentifier() or keyword.iskeyword(new.lower) or new.lower != new.lower.lower():
        errors.append(f"{new.lower!r} is not usable as a lowercase Python package name")
    if new.lower in sys.stdlib_module_names:
        errors.append(f"{new.lower!r} would shadow the standard-library module of that name")
    if new.lower in reserved:
        errors.append(f"{new.lower!r} is already a top-level name in this repository")
    if not re.fullmatch(r"[A-Z][A-Z0-9]*", new.upper):
        errors.append(f"{new.upper!r} is not usable as an environment-variable prefix (A-Z, 0-9)")
    if not re.fullmatch(r"[a-z][a-z0-9-]*", new.kebab):
        errors.append(f"{new.kebab!r} is not usable as a kebab-case name")
    a, b = (re.sub(r"[-_ ]", "", f.lower).casefold() for f in (old, new))
    if a in b or b in a:
        errors.append("the old and new names must not contain each other: the rename could not be repeated")
    return errors


# ------------------------------------------------------------------------------ spans


def merge_spans(spans: list[Span]) -> list[Span]:
    out: list[Span] = []
    for start, end in sorted(spans):
        if out and start <= out[-1][1]:
            out[-1] = (out[-1][0], max(out[-1][1], end))
        else:
            out.append((start, end))
    return out


def overlaps(spans: list[Span], start: int, end: int) -> bool:
    """Whether [start, end) touches any of `spans` (sorted and merged)."""
    i = bisect.bisect_right(spans, (start, sys.maxsize)) - 1
    return any(0 <= j < len(spans) and spans[j][0] < end and start < spans[j][1] for j in (i, i + 1))


def keep_spans(text: str) -> list[Span]:
    """Lines carrying the keep pragma, and blocks from ``keep-begin`` to ``keep-end``."""
    spans = []
    offset, start = 0, None
    for line in text.splitlines(keepends=True):
        end = offset + len(line)
        mark = KEEP.search(line)
        if start is not None:
            if mark and mark.group("edge") == "-end":
                spans.append((start, end))
                start = None
        elif mark and mark.group("edge") == "-begin":
            start = offset
        elif mark and mark.group("edge") is None:
            spans.append((offset, end))
        offset = end
    if start is not None:  # unterminated: protect to the end rather than guess
        spans.append((start, len(text)))
    return spans


def literal_spans(text: str, literals: list[str]) -> list[Span]:
    spans = []
    for literal in literals:
        start = text.find(literal)
        while start != -1:
            spans.append((start, start + len(literal)))
            start = text.find(literal, start + len(literal))
    return spans


def pattern_spans(text: str, pattern: re.Pattern[str]) -> list[Span]:
    return [m.span() for m in pattern.finditer(text)]


def markdown_sections(text: str, titles: list[str]) -> list[tuple[int, int, int]]:
    """(heading start, heading end, section end) for each section titled one of `titles`."""
    wanted = {t.casefold() for t in titles}
    if not wanted:
        return []
    lines = markdown_lines(text)
    found = []
    for i, (start, end, heading) in enumerate(lines):
        if heading and heading.group(2).casefold() in wanted:
            level = len(heading.group(1))
            stop = next((s for s, _, h in lines[i + 1 :] if h and len(h.group(1)) <= level), len(text))
            found.append((start, end, stop))
    return found


def markdown_lines(text: str) -> list[tuple[int, int, re.Match[str] | None]]:
    """(start, end, heading match or None) per line, ignoring headings inside code fences."""
    lines, offset, fenced = [], 0, False
    for line in text.splitlines(keepends=True):
        if FENCE.match(line):
            fenced = not fenced
        heading = None if fenced else HEADING.match(line)
        lines.append((offset, offset + len(line), heading))
        offset += len(line)
    return lines


def protected_spans(text: str, literals: list[str], sections: list[str]) -> list[Span]:
    """Everything a rewrite must leave alone in one living file."""
    spans = keep_spans(text) + literal_spans(text, literals) + pattern_spans(text, PREVIOUSLY)
    return spans + [(start, stop) for start, _, stop in markdown_sections(text, sections)]


def blank_out(text: str, spans: list[Span]) -> str:
    """`text` with `spans` blanked, newlines kept, so line numbers still line up."""
    chars = list(text)
    for start, end in merge_spans(spans):
        for k in range(start, end):
            if chars[k] != "\n":
                chars[k] = " "
    return "".join(chars)


# ------------------------------------------------------------------------------ rewriting


@dataclass
class Hit:
    line: int
    old: str
    new: str
    token: str
    kind: str


def token_at(text: str, start: int, end: int, chars: frozenset[str] = TOKEN_CHARS) -> str:
    """The run of `chars` around [start, end): a path, URL, dotted name or identifier."""
    left, right = start, end
    while left > 0 and text[left - 1] in chars:
        left -= 1
    while right < len(text) and text[right] in chars:
        right += 1
    return text[left:right].strip(".:,;")


def classify(path: str, line: str, token: str, matched: str, old: Forms, word: str | None = None) -> str:
    """The kind of change one replacement is, for the plan. Descriptive only."""
    name = path.rsplit("/", 1)[-1]
    low = re.escape(old.lower)
    if name == "pyproject.toml":
        return "distribution & scripts"
    if (
        path.startswith(("plugins/", ".agents/", ".claude-plugin/", ".codex-plugin/"))
        or name == "marketplace.json"
    ):
        return "plugin & marketplace"
    if "://" in token or "github.com/" in token:
        return "URL"
    if matched in (old.upper, old.upper_snake):
        return "env var"
    if name == ".gitignore" or re.search(rf"(^|/)\.{low}\b|\b{low}\.db\b", token):
        return "data dir"
    if path.endswith(".py") and re.match(rf"\s*(from|import)\s+{low}\b", line):
        return "python import"
    if "/" not in token and re.search(rf"(?<![\w-]){low}(\.[A-Za-z_]\w*)+", token):
        return "module path"
    if "/" in token:
        return "path"
    if token.startswith("X-"):
        return "ownership marker"
    if (word or token) != matched and re.fullmatch(r"\w+", word or token):
        return "identifier"
    if matched in (old.lower, old.kebab) or re.fullmatch(rf"{low}(-[a-z0-9]+)+(@[\w-]+)?", token):
        return "command & package name"
    if matched in (old.display, old.spaced, old.title):
        return "prose"
    return "other"


def substitute(
    text: str,
    path: str,
    pattern: re.Pattern[str],
    pairs: dict[str, str],
    protected: list[Span],
    old: Forms,
) -> tuple[str, list[Hit]]:
    """Rewrite every spelling outside `protected`, in one pass."""
    protected = merge_spans(protected)
    line_starts = [0] + [m.end() for m in re.finditer("\n", text)]
    out, hits, last = [], [], 0
    for match in pattern.finditer(text):
        start, end = match.span()
        if overlaps(protected, start, end):
            continue
        number = bisect.bisect_right(line_starts, start)
        line_end = text.find("\n", start)
        line = text[line_starts[number - 1] : len(text) if line_end == -1 else line_end]
        token = token_at(text, start, end)
        word = token_at(text, start, end, WORD_CHARS)
        replacement = pairs[match.group()]
        out += [text[last:start], replacement]
        kind = classify(path, line, token, match.group(), old, word)
        hits.append(Hit(number, match.group(), replacement, token, kind))
        last = end
    out.append(text[last:])
    return "".join(out), hits


def rename_text(text: str, pattern: re.Pattern[str], pairs: dict[str, str]) -> str:
    return pattern.sub(lambda m: pairs[m.group()], text)


def rename_path(
    path: str, pattern: re.Pattern[str], pairs: dict[str, str], keep_basename: bool = False
) -> str:
    parts = path.split("/")
    head = [rename_text(p, pattern, pairs) for p in parts[:-1]]
    return "/".join([*head, parts[-1] if keep_basename else rename_text(parts[-1], pattern, pairs)])


def plan_moves(targets: dict[str, str], rename_dir: Callable[[str], str]) -> list[tuple[str, str, bool]]:
    """Ordered ``(source, destination, is_directory)`` moves, each in the tree as it is then.

    A directory whose tracked files all move under its new name moves as one, parents first,
    so untracked contents such as caches go with it. Everything else moves file by file.
    """
    if all(src == dst for src, dst in targets.items()):
        return []
    directories = set()
    for path in targets:
        parts = path.split("/")[:-1]
        directories.update("/".join(parts[: i + 1]) for i in range(len(parts)))
    done: list[tuple[str, str]] = []

    def current(path: str) -> str:
        best = None
        for orig, dest in done:
            if (path == orig or path.startswith(orig + "/")) and (best is None or len(orig) > len(best[0])):
                best = (orig, dest)
        return path if best is None else best[1] + path[len(best[0]) :]

    moves: list[tuple[str, str, bool]] = []
    for directory in sorted(directories, key=lambda d: (d.count("/"), d)):
        destination = rename_dir(directory)
        if destination.rsplit("/", 1)[-1] == directory.rsplit("/", 1)[-1]:
            continue
        inside = [f for f in targets if f.startswith(directory + "/")]
        if inside and all(targets[f].startswith(destination + "/") for f in inside):
            moves.append((current(directory), destination, True))
            done.append((directory, destination))
    for path, destination in sorted(targets.items()):
        if current(path) != destination:
            moves.append((current(path), destination, False))
    return moves


